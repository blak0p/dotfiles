#!/usr/bin/env python3
"""Keyboard layouts, key repeat and shell language for the sky Settings window.

  sky_input.py layouts                     -> JSON [{code, name}] from the xkb rules
  sky_input.py variants LAYOUT             -> JSON [{code, name}] ("" = default first)
  sky_input.py save FILE --json MODEL [--dry-run]
                                           -> write FILE (the user layer input.lua, keeps FILE.bak)
  sky_input.py eval --json MODEL           -> the same hl.config Lua without header, for `hyprctl eval`
  sky_input.py language FILE auto|en|es    -> merge "language" into settings.json

MODEL = {"layouts": [{"layout": "us", "variant": "intl"}], "rate": 35, "delay": 250}.
Every value is checked against the xkb list / integer ranges before any Lua is
generated, so no input can inject code. Rules file: $SKY_XKB_RULES or
/usr/share/X11/xkb/rules/evdev.lst.
"""
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

RULES_FILE = "/usr/share/X11/xkb/rules/evdev.lst"
RATE = (1, 100)
DELAY = (100, 2000)
LANGUAGES = ("auto", "en", "es")
HEADER = (
    "-- Generated by sky Settings (Keyboard); do not edit by hand.\n"
    "-- Changes made here are overwritten the next time the page saves.\n"
)


def parse_rules(text: str) -> dict:
    layouts, variants, section = {}, {}, None
    for line in text.splitlines():
        if line.startswith("!"):
            section = line[1:].strip()
            continue
        if not line.strip() or section not in ("layout", "variant"):
            continue
        code, _, rest = line.strip().partition(" ")
        rest = rest.strip()
        if section == "layout":
            layouts[code] = rest
        else:
            lay, sep, name = rest.partition(": ")
            if sep:
                variants.setdefault(lay.strip(), {})[code] = name.strip()
    return {"layouts": layouts, "variants": variants}


def load_rules() -> dict:
    path = os.environ.get("SKY_XKB_RULES") or RULES_FILE
    return parse_rules(Path(path).read_text(errors="replace"))


def _int(value, name, lo, hi) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not lo <= value <= hi:
        raise ValueError("%s must be an integer between %d and %d" % (name, lo, hi))
    return value


def _validate(model, xkb):
    if not isinstance(model, dict):
        raise ValueError("model must be an object")
    items = model.get("layouts")
    if not isinstance(items, list) or not items:
        raise ValueError("at least one keyboard layout is required")
    codes, vars_ = [], []
    for it in items:
        if not isinstance(it, dict):
            raise ValueError("invalid layout entry")
        lay, var = it.get("layout"), it.get("variant", "")
        if not isinstance(lay, str) or lay not in xkb["layouts"]:
            raise ValueError("unknown keyboard layout: %r" % (lay,))
        if not isinstance(var, str) or (var and var not in xkb["variants"].get(lay, {})):
            raise ValueError("unknown variant %r for layout %s" % (var, lay))
        codes.append(lay)
        vars_.append(var)
    if "rate" not in model or "delay" not in model:
        raise ValueError("rate and delay are required")
    return codes, vars_, _int(model["rate"], "rate", *RATE), _int(model["delay"], "delay", *DELAY)


def render(model, xkb, header: bool = True) -> str:
    codes, vars_, rate, delay = _validate(model, xkb)
    body = (
        "hl.config({\n"
        "    input = {\n"
        '        kb_layout = "%s",\n'
        '        kb_variant = "%s",\n'
        "        repeat_rate = %d,\n"
        "        repeat_delay = %d\n"
        "    }\n"
        "})\n"
    ) % (",".join(codes), ",".join(vars_), rate, delay)
    return (HEADER + "\n" + body) if header else body


def _atomic_write(target: Path, data: str):
    fd, tmp = tempfile.mkstemp(dir=str(target.parent), prefix=target.name + ".")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        if target.exists():
            shutil.copymode(target, tmp)
        os.replace(tmp, target)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def save(path, model, xkb, dry_run: bool = False) -> str:
    new = render(model, xkb)  # validates before touching anything
    if not dry_run:
        real = Path(path).resolve()
        real.parent.mkdir(parents=True, exist_ok=True)
        if real.is_file():
            _atomic_write(real.with_name(real.name + ".bak"), real.read_text())
        _atomic_write(real, new)
    return new


def set_language(path, lang: str):
    if lang not in LANGUAGES:
        raise ValueError("language must be one of: %s" % ", ".join(LANGUAGES))
    real = Path(path).resolve()
    data = {}
    if real.is_file():
        try:
            data = json.loads(real.read_text())
        except ValueError:
            raise ValueError("%s is not valid JSON; not touching it" % path)
        if not isinstance(data, dict):
            raise ValueError("%s is not a JSON object; not touching it" % path)
    data["language"] = lang
    real.parent.mkdir(parents=True, exist_ok=True)
    if real.is_file():
        _atomic_write(real.with_name(real.name + ".bak"), real.read_text())
    _atomic_write(real, json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def _model(args):
    if "--json" not in args or args.index("--json") + 1 >= len(args):
        raise ValueError("missing --json MODEL")
    try:
        return json.loads(args[args.index("--json") + 1])
    except ValueError:
        raise ValueError("invalid JSON")


def _run(cmd, args) -> int:
    if cmd == "layouts":
        xkb = load_rules()
        print(json.dumps([{"code": c, "name": n} for c, n in sorted(xkb["layouts"].items(), key=lambda x: x[1].lower())]))
    elif cmd == "variants" and len(args) == 1:
        xkb = load_rules()
        if args[0] not in xkb["layouts"]:
            raise ValueError("unknown keyboard layout: %r" % args[0])
        vs = sorted(xkb["variants"].get(args[0], {}).items(), key=lambda x: x[1].lower())
        print(json.dumps([{"code": "", "name": ""}] + [{"code": c, "name": n} for c, n in vs]))
    elif cmd == "save" and len(args) >= 3 and args[1] == "--json":
        dry = "--dry-run" in args
        out = save(args[0], _model(args), load_rules(), dry)
        if dry:
            print(out, end="")
    elif cmd == "eval" and args and args[0] == "--json":
        print(render(_model(args), load_rules(), header=False), end="")
    elif cmd == "language" and len(args) == 2:
        set_language(args[0], args[1])
    else:
        print(__doc__)
        return 2
    return 0


def main(argv) -> int:
    if len(argv) < 2:
        print(__doc__)
        return 2
    try:
        return _run(argv[1], argv[2:])
    except (ValueError, OSError) as e:
        print("sky_input: %s" % e, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
