#!/usr/bin/env python3
"""Appearance helper for the sky settings Appearance page.

Everything is saved in the user layer, never in tracked repo files:
  GTK / icon theme   -> gsettings (dconf, per user)
  cursor theme/size  -> gsettings + `hyprctl setcursor` live, persisted in the
                        Settings-owned ~/.config/sky/hypr/appearance.lua
  palette options    -> ~/.config/sky/theme.json (read by sky_theme.py)
Qt apps take their theme from qt6ct (a repo file): not written here.

  sky_appearance.py scan                         -> JSON {gtk, icons, cursors, sizes, schemes}
  sky_appearance.py gtk NAME | icons NAME        -> apply an installed theme
  sky_appearance.py cursor NAME SIZE             -> apply + persist
  sky_appearance.py palette SCHEME [#rrggbb|auto] -> save theme.json
Every name is validated against the installed lists; nothing else reaches Lua or a command.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HOME = Path.home()
CONFIG_HOME = Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config")
DATA_HOME = Path(os.environ.get("XDG_DATA_HOME") or HOME / ".local/share")
APPEARANCE_FILE = CONFIG_HOME / "sky/hypr/appearance.lua"
THEME_FILE = CONFIG_HOME / "sky/theme.json"
THEME_DIRS = [Path("/usr/share/themes"), HOME / ".themes", DATA_HOME / "themes"]
ICON_DIRS = [Path("/usr/share/icons"), HOME / ".icons", DATA_HOME / "icons"]
SIZES = [16, 24, 32, 36, 40, 48, 64, 96]
SCHEMES = ["scheme-tonal-spot", "scheme-vibrant", "scheme-expressive", "scheme-fidelity",
           "scheme-content", "scheme-neutral", "scheme-monochrome"]
SCHEMA = "org.gnome.desktop.interface"
HEADER = "-- Generated by Sky Settings (Appearance). Do not edit: changes are overwritten.\n"


def _subdirs(roots):
    seen = {}
    for root in roots:
        try:
            for d in sorted(root.iterdir()):
                if d.is_dir():
                    seen.setdefault(d.name, d)
        except OSError:
            pass
    return seen


def _has_directories(index: Path) -> bool:
    try:
        return any(l.strip().startswith("Directories=") and l.split("=", 1)[1].strip()
                   for l in index.read_text(errors="replace").splitlines())
    except OSError:
        return False


def scan(theme_dirs=None, icon_dirs=None) -> dict:
    themes = _subdirs(THEME_DIRS if theme_dirs is None else theme_dirs)
    icons = _subdirs(ICON_DIRS if icon_dirs is None else icon_dirs)
    return {
        "gtk": sorted(n for n, d in themes.items()
                      if (d / "gtk-3.0").is_dir() or (d / "gtk-4.0").is_dir()),
        "icons": sorted(n for n, d in icons.items() if _has_directories(d / "index.theme")),
        "cursors": sorted(n for n, d in icons.items() if (d / "cursors").is_dir()),
    }


def _run(argv):
    return subprocess.run(argv, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                          check=False, timeout=10).returncode


def _fail(msg: str) -> int:
    print(f"sky_appearance: {msg}", file=sys.stderr)
    return 1


def write_atomic(out: Path, text: str) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.is_file():
        shutil.copy2(out, str(out) + ".bak")
    fd, tmp = tempfile.mkstemp(dir=out.parent, prefix=f".{out.name}-")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.replace(tmp, out)


def set_gsetting(key: str, name: str, theme_dirs=None, icon_dirs=None, run=_run) -> int:
    if key not in ("gtk-theme", "icon-theme"):
        return _fail("unknown setting")
    found = scan(theme_dirs, icon_dirs)["gtk" if key == "gtk-theme" else "icons"]
    if name not in found:
        return _fail(f"{key}: not installed: {name!r}")
    run(["gsettings", "set", SCHEMA, key, name])
    return 0


def save_cursor(file: Path, theme: str, size, theme_dirs=None, icon_dirs=None, run=_run) -> int:
    if theme not in scan(theme_dirs, icon_dirs)["cursors"]:
        return _fail(f"cursor theme not installed: {theme!r}")
    if isinstance(size, bool) or not re.fullmatch(r"[0-9]{1,3}", str(size)) or not 8 <= int(size) <= 256:
        return _fail(f"invalid cursor size: {size!r}")
    size = int(size)
    write_atomic(file, HEADER + "".join(
        f'hl.env("{k}", "{v}")\n' for k, v in (
            ("XCURSOR_THEME", theme), ("XCURSOR_SIZE", size),
            ("HYPRCURSOR_THEME", theme), ("HYPRCURSOR_SIZE", size))))
    run(["hyprctl", "setcursor", theme, str(size)])
    run(["gsettings", "set", SCHEMA, "cursor-theme", theme])
    run(["gsettings", "set", SCHEMA, "cursor-size", str(size)])
    return 0


def save_palette(file: Path, scheme: str, accent) -> int:
    if scheme not in SCHEMES:
        return _fail(f"unknown scheme: {scheme!r}")
    if accent is not None and not re.fullmatch(r"#[0-9a-fA-F]{6}", str(accent)):
        return _fail(f"invalid accent: {accent!r}")
    write_atomic(file, json.dumps({"scheme": scheme, "accent": accent.lower() if accent else None},
                                  indent=2) + "\n")
    return 0


def main(argv) -> int:
    cmd, args = (argv[0] if argv else ""), argv[1:]
    if cmd == "scan" and not args:
        print(json.dumps({**scan(), "sizes": SIZES, "schemes": SCHEMES}))
        return 0
    if cmd in ("gtk", "icons") and len(args) == 1:
        return set_gsetting("gtk-theme" if cmd == "gtk" else "icon-theme", args[0])
    if cmd == "cursor" and len(args) == 2:
        return save_cursor(APPEARANCE_FILE, args[0], args[1])
    if cmd == "palette" and len(args) in (1, 2):
        accent = None if len(args) == 1 or args[1] == "auto" else args[1]
        return save_palette(THEME_FILE, args[0], accent)
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
